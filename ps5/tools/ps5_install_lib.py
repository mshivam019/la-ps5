    p.add_argument('--data', type=Path, help='Optional already prepared Animal Crossing data folder')
    p.add_argument('--eboot-only', action='store_true')
    p.add_argument('--no-launch', action='store_true', help=argparse.SUPPRESS)
    p.add_argument('--engine', help=argparse.SUPPRESS)  # Old upload engine is no longer required.
