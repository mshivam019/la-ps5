def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def files(root):
    if root.is_symlink():
        raise ValueError('Choose real files/folders, not symbolic links: ' + str(root))
    if root.is_file():
        return [root]
    if not root.is_dir():
        raise ValueError('Folder does not exist: ' + str(root))
    result = []
    for p in sorted(root.rglob('*')):
        if p.is_symlink():
            raise ValueError('Symbolic link in selected folder: ' + str(p))
        if p.is_file():
            result.append(p)
    return result


def child(root, name):
    """Resolve a required leaf case-insensitively without inventing a path."""
    matches = [p for p in root.iterdir() if p.name.casefold() == name.casefold()]
    if len(matches) != 1:
        raise ValueError('Expected exactly one ' + name + ' in ' + str(root))
    return matches[0]


def game_files(title, source):
    _, kind, target = PORTS[title]
    if source.is_symlink():
        raise ValueError('Game input must not be a symbolic link')
    if title in ('PPSA99640', 'PPSA99660'):
        with source.open('rb') as stream:
            header = stream.read(0x460)
        disc = b'GZ2E01' if title == 'PPSA99640' else b'GAFE01'
        if (len(header) != 0x460 or header[:6] != disc or header[7] != 0 or
                header[0x1c:0x20] != bytes.fromhex('c2339f3d')):
            raise ValueError('Expected an uncompressed ' + kind +
                             '. Convert RVZ/CISO with Dolphin first; renaming is insufficient.')
        import struct
        dol, fst, length = struct.unpack_from('>III', header, 0x420)
        size = source.stat().st_size
        if dol < 0x460 or dol + 0x100 > size or fst + length > size or length < 12:
            raise ValueError('The disc image is truncated or its file table is invalid')
        return [(source, target)]
    if title in ('PPSA99620', 'PPSA99621'):
        source = child(source, kind) if source.is_dir() else source
        if source.name.casefold() != kind or not zipfile.is_zipfile(source):
            raise ValueError('Choose ' + kind + ' generated by the matching desktop port, not a raw ROM')
        with zipfile.ZipFile(source) as archive:
            bad = archive.testzip()
            if bad is not None:
                raise ValueError('Damaged game archive: ' + bad)
            if not archive.namelist():
                raise ValueError('The game archive is empty')
        return [(source, target)]
    if not source.is_dir():
        raise ValueError('Choose the ' + kind + ', not the original disc/package file')
    if title == 'PPSA99630':
        if not any(p.name.casefold() == 'morrowind.esm' for p in source.iterdir()):
            source = child(source, 'Data Files')
        for required in ('Morrowind.esm', 'Tribunal.esm', 'Bloodmoon.esm',
                         'Morrowind.bsa', 'Tribunal.bsa', 'Bloodmoon.bsa'):
            if not child(source, required).is_file():
                raise ValueError('Incomplete Data Files: ' + required)
    elif title == 'PPSA99641':
        if not (source / 'game.wwhd').is_file():
            source = source / 'game'
        for required in ('game.wwhd', 'code/cking.rpx'):
            if not (source / required).is_file():
                raise ValueError('Missing ' + required + '. Run the matching Wind Waker HD setup first.')
        for required in ('content', 'meta'):
            if not (source / required).is_dir():
                raise ValueError('Missing ' + required + ' in prepared game folder')
    elif title == 'PPSA99670':
        if not (source / 'game.la').is_file():
            source = source / 'extracted'
        for required in ('game.la', 'exefs/main', 'exefs/sdk', 'romfs.bin'):
            if not (source / required).is_file():
                raise ValueError('Missing ' + required + '. Run the matching Link\'s Awakening setup first.')
        if not (source / 'romfs/region_common').is_dir():
            raise ValueError('Missing extracted RomFS; run the matching setup first')
    selected = files(source)
    if not selected:
        raise ValueError('The selected game folder is empty')
    # Normalize master/archive names used by the shipped case-sensitive OpenMW config.
    canonical = {n.casefold(): n for n in ('Morrowind.esm', 'Tribunal.esm', 'Bloodmoon.esm',
                                          'Morrowind.bsa', 'Tribunal.bsa', 'Bloodmoon.bsa')}
    return [(p, target + '/' + (canonical.get(p.name.casefold(), p.name)
             if title == 'PPSA99630' and p.parent == source else p.relative_to(source).as_posix()))
            for p in selected]


def personal_path(relative, title):
    # Dusklight ships its default config in user/. Include it for a fresh copy,
    # but never overwrite an existing config during optional FTP updates.
    if title == 'PPSA99640' and relative.as_posix() == 'user/config.json':
        return False
    return any(s.casefold() in {'user', 'userdata', 'save', 'saves', 'cache', '.git'}
               for s in relative.parts)


def unpack_app(source, title, temporary):
    if source.is_file():
        with zipfile.ZipFile(source) as z:
            entries = z.infolist()
            for info in entries:
                path = PurePosixPath(info.filename)
                if (path.is_absolute() or '..' in path.parts or '\\' in info.filename or
                        ':' in info.filename or stat.S_ISLNK(info.external_attr >> 16)):
                    raise ValueError('Unsafe archive path: ' + info.filename)
            prefixes = (title + '/', 'output/' + title + '/')
            prefix = next((p for p in prefixes if p + 'eboot.bin' in z.namelist()), None)
            if prefix is None:
                raise ValueError('ZIP must contain ' + title + '/eboot.bin (optionally under output/)')
            picked = [i for i in entries if i.filename.startswith(prefix) and not i.is_dir()]
            if sum(i.file_size for i in picked) > shutil.disk_usage(temporary).free:
                raise ValueError('Not enough temporary disk space to unpack the app')
            root = temporary / 'app'
            root.mkdir()
            for info in picked:
                dest = root.joinpath(*PurePosixPath(info.filename[len(prefix):]).parts)
                dest.parent.mkdir(parents=True, exist_ok=True)
                with z.open(info) as src, dest.open('xb') as dst:
                    shutil.copyfileobj(src, dst, 1024 * 1024)
    else:
        root = source
        if not (root / 'eboot.bin').is_file():
            candidates = (source / title, source / 'output' / title)
            root = next((p for p in candidates if (p / 'eboot.bin').is_file()), root)
    files(root)  # Reject symlinks before reading metadata or transferring anything.
    if not (root / 'eboot.bin').is_file() or not (root / 'sce_sys/icon0.png').is_file():
        raise ValueError('App folder must include eboot.bin and sce_sys/icon0.png')
    meta = json.loads((root / 'sce_sys/param.json').read_text(encoding='utf-8'))
    if meta.get('titleId') != title:
        raise ValueError('Selected app belongs to another title')
    # Never carry saved sessions, keys or executable backups into a new installation.
    result = []
    for p in files(root):
        rel = p.relative_to(root)
        if personal_path(rel, title) or '.before-' in p.name:
            continue
        result.append((p, rel.as_posix()))
    return result


def local_copy(items, output, title):
    target = output / title
    if target.exists():
        raise ValueError('Output already exists. Choose a new folder to preserve its files: ' + str(target))
    if any(target.resolve() == p.resolve() or target.resolve() in p.resolve().parents for p, _ in items):
        raise ValueError('Output must be outside the selected input')
    output.mkdir(parents=True, exist_ok=True)
    if sum(p.stat().st_size for p, _ in items) > shutil.disk_usage(output).free:
        raise ValueError('Not enough free space at the selected output')
    target.mkdir()
    inventory = []
    for index, (source, rel) in enumerate(items, 1):
        destination = target / rel
        destination.parent.mkdir(parents=True, exist_ok=True)
        print('[%d/%d] Copying %s (%.1f MiB)...' % (index, len(items), rel, source.stat().st_size / 1048576), flush=True)
        shutil.copy2(source, destination)
        sha256 = digest(source)
        if sha256 != digest(destination):
            raise ValueError('Copy checksum mismatch: ' + rel)
        inventory.append({'path': rel, 'size': destination.stat().st_size, 'sha256': sha256})
        print('[%d/%d] Copied %s' % (index, len(items), rel), flush=True)
    return inventory


def copy_instructions(target, title):
    print('Ready: ' + str(target.resolve()))
    print('Copy its CONTENTS into your installed ' + title + ' folder using your console file manager.')
    print('A USB staging folder is not automatically installed or registered as a PS5 title.')


def remote_exists(ftp, path):
    try:
        value = ftp.size(path)
        return value is not None and 0 <= value < (1 << 63)
    except ftplib.error_perm as e:
        if not str(e).startswith('550'):
            raise
    return False


def remote_directory(ftp, path, known):
    current = ''
    for part in path.split('/'):
        if part:
            current += '/' + part
            if current not in known:
                try:
                    ftp.mkd(current)
                except ftplib.error_perm:
                    ftp.cwd(current)  # Fails rather than hiding a permission error.
                known.add(current)


def ftp_copy(items, args):
    if not args.closed:
        raise ValueError('Save and close the game, then add --closed to confirm before FTP transfer')
    path = PurePosixPath(args.remote_dir or '')
    if not path.is_absolute() or '..' in path.parts or path.name != args.title:
        raise ValueError('--remote-dir must be the full installed title path ending in ' + args.title)
    if any(c in str(path) for c in ('\r', '\n', '\\')):
        raise ValueError('Invalid remote path')
    host = args.console
    if '://' in host or '/' in host or any(c in host for c in ('\r', '\n')):
        raise ValueError('--console takes an IP address or hostname, not a URL')
    password = getpass.getpass('FTP password: ') if args.ftp_user != 'anonymous' else 'anonymous@'
    stamp = uuid.uuid4().hex[:12]
    known = set()
    kept = 0
    with ftplib.FTP() as ftp:
        ftp.connect(host, args.ftp_port, timeout=60)
        ftp.login(args.ftp_user, password)
        ftp.voidcmd('TYPE I')
        for index, (source, rel) in enumerate(sorted(items, key=lambda x: (x[1] == 'eboot.bin', x[1])), 1):
            target = str(path) + '/' + rel
            remote_directory(ftp, target.rsplit('/', 1)[0], known)
            present = remote_exists(ftp, target)
            # Existing settings, game data and modules are preserved unless the user
            # deliberately selected replacement. Never delete another remote file.
            config_file = rel in ('user/config.json', 'assets/openmw.cfg', 'assets/settings.cfg', 'data/settings.ini')
            if present and (config_file or not args.replace_existing):
                kept += 1
                print('Kept existing ' + rel + (' (configuration preserved)' if config_file else ' (use --replace-existing to replace with a backup)'))
                continue
            temporary = target + '.upload-' + stamp
            expected = source.stat().st_size
            sent = 0
            def count(chunk):
                nonlocal sent
                sent += len(chunk)
            with source.open('rb') as stream:
                ftp.storbinary('STOR ' + temporary, stream, 1024 * 1024, callback=count)
            if sent != expected:
                raise ValueError('Transfer byte count mismatch: ' + rel)
            stored = ftp.size(temporary)
            if stored != expected:
                # Some PS5 FTP servers expose a decoded SELF size via SIZE.
                # A raw directory entry may still report its stored size.
                try:
                    name = temporary.rsplit('/', 1)[1]
                    stored = next(int(f['size']) for n, f in ftp.mlsd(temporary.rsplit('/', 1)[0]) if n == name)
                except (ftplib.error_perm, StopIteration, KeyError, ValueError):
                    stored = None
                if stored != expected:
                    # Older console servers may support LIST but not MLSD.
                    listing = []
                    try:
                        ftp.retrlines('LIST ' + temporary, listing.append)
                        for line in listing:
                            fields = line.split(None, 8)
                            if len(fields) == 9 and fields[0].startswith('-'):
                                if fields[8] in (temporary, temporary.rsplit('/', 1)[1]):
                                    stored = int(fields[4])
                                    break
                    except (ftplib.error_perm, ValueError):
                        pass
                if stored != expected:
                    raise ValueError('FTP cannot verify stored size for ' + rel +
                                     '. Original file was kept; use the local/USB copy route or another FTP server.')
            backup = target + '.before-install-' + stamp
            if present:
                ftp.rename(target, backup)
            try:
                ftp.rename(temporary, target)
            except Exception:
                if present:
                    ftp.rename(backup, target)
                raise
            print('[%d/%d] Uploaded %s' % (index, len(items), rel), flush=True)
    print('Transfer complete (%d existing files kept). No title was closed, registered or launched.' % kept)
    print('If new, refresh/mount it with your existing native-title loader. PS5 Upload is optional.')


def interactive():
    print('PS5 port file helper ' + VERSION)
    for title, (name, kind, _) in PORTS.items():
        print('  ' + title + '  ' + name + ' — ' + kind)
    title = input('Title ID: ').strip().upper()
    if title not in PORTS:
        raise ValueError('Choose a listed title ID')
    def choose(prompt):
        return input(prompt).strip().strip('\"').strip("'")
    game = choose('Game file/prepared folder (blank to copy app only): ')
    app = choose('App ZIP/folder (blank if already installed from the store): ')
    output = choose('New output folder on this computer or USB drive: ')
    if not output:
        raise ValueError('Choose an output folder')
    args = ['--title', title, '--output', output]
    if game:
        args += ['--game', game]
    if app:
        args += ['--app', app]
    return args


def prepare_main(argv=None):
    p = argparse.ArgumentParser(description='Prepare a ready-to-copy PS5 title folder locally. No console/network access.')
    p.add_argument('--version', action='version', version=VERSION)
    p.add_argument('--title', choices=PORTS, required=True)
    p.add_argument('--app', type=Path, help='Optional precompiled app ZIP/folder; select it for a full installation')
    p.add_argument('--game', type=Path, help='Game file or already prepared game folder; see INSTALL.md')
    p.add_argument('--output', type=Path, required=True, help='New local or USB parent folder')
    p.add_argument('--check', action='store_true', help='Validate inputs and show the plan without copying')
    args = p.parse_args(interactive() if argv is None and len(sys.argv) == 1 else argv)
    if not args.app and not args.game:
        p.error('Select --app and/or --game')
    if args.app and (args.app.is_symlink() or not args.app.exists()):
        p.error('--app must be a real ZIP or folder')
    if args.game and not args.game.exists():
        p.error('--game does not exist')
    target = (args.output / args.title).resolve()
    for source in (args.app, args.game):
        if source and source.is_dir() and (target == source.resolve() or source.resolve() in target.parents):
            p.error('Choose an output outside the selected input folder')
    with tempfile.TemporaryDirectory(prefix='ps5-prepare-') as work:
        items = unpack_app(args.app, args.title, Path(work)) if args.app else []
        if args.game:
            items += game_files(args.title, args.game)
        selected = {rel: source for source, rel in items}
        items = [(source, rel) for rel, source in sorted(selected.items())]
        validate_names(items)
        if not items:
            raise ValueError('No files selected')
        print('%s: %d files, %.1f MiB.' %
              (args.title, len(items), sum(p.stat().st_size for p, _ in items) / 1048576), flush=True)
        if args.check:
            for _, rel in items[:20]:
                print('  ' + rel)
            return
        manifest = args.output / ('MANIFEST-' + args.title + '.json')
        if manifest.exists():
            raise ValueError('Manifest already exists; choose a new output folder: ' + str(manifest))
        inventory = local_copy(items, args.output, args.title)
        with manifest.open('x', encoding='utf-8') as stream:
            json.dump({'schema': 1, 'helper_version': VERSION, 'title': args.title,
                       'mode': 'full' if args.app and args.game else 'app' if args.app else 'game',
                       'files': inventory}, stream, indent=2)
            stream.write('\n')
        copy_instructions(args.output / args.title, args.title)
        print('Keep the checksum manifest beside the title folder: ' + str(manifest))
        print('Recheck anytime: python3 validate-files.py --src "' + str(args.output / args.title) + '"')
        note = ('Full app and selected game files.' if args.app and args.game else
                'Game-data overlay only: merge into the already installed app.' if args.game else
                'App only: the game files described in INSTALL.md are still required.')
        instructions = args.output / ('COPY-' + args.title + '-TO-PS5.txt')
        instructions.write_text(note + '\nCopy the CONTENTS of ' + args.title +
            ' into its installed title folder. Do not nest title folders.\n'
            'Copy using your preferred method: USB/file manager or FTP over Wi-Fi/Ethernet.\n'
            'A local/USB output folder is not automatically registered as a title.\n'
            'Preserve existing saves/settings. No console was contacted.\n'
            'Keep MANIFEST-' + args.title + '.json beside this folder for validate-files.py.\n'
            'The manifest is a desktop verification file; do not copy it into the title.\n', encoding='utf-8')
        print(note)


def validate_names(items):
    seen = set()
    for _, rel in items:
        if (not rel or PurePosixPath(rel).is_absolute() or
                any(c in rel for c in ('\r', '\n', '\\', ':')) or
                any(part in ('', '.', '..') for part in rel.split('/')) or
                rel.casefold() in seen):
            raise ValueError('Unsupported or case-colliding filename in input: ' + rel)
        seen.add(rel.casefold())


def transfer_main(argv=None):
    p = argparse.ArgumentParser(description='Optional FTP copy of an already prepared PS5 title folder. No compilation or game extraction.')
    p.add_argument('--version', action='version', version=VERSION)
    p.add_argument('--src', required=True, type=Path, help='Ready-to-copy PPSAxxxxx folder, including a data-only overlay')
    p.add_argument('--console', required=True, help='FTP IP address/hostname over Wi-Fi or Ethernet')
    p.add_argument('--remote-dir', required=True, help='Full installed title path, including its PPSAxxxxx folder')
    p.add_argument('--ftp-port', type=int, default=2121)
    p.add_argument('--ftp-user', default='anonymous')
    p.add_argument('--closed', action='store_true', help='Confirm you saved and closed this game')
    p.add_argument('--replace-existing', action='store_true', help='Replace selected remote files, retaining backups')
    p.add_argument('--check', action='store_true', help='Validate the local transfer plan without connecting')
    args = p.parse_args(argv)
    args.title = args.src.name
    if args.title not in PORTS:
        p.error('--src must be the prepared PPSAxxxxx folder, not its parent')
    path = PurePosixPath(args.remote_dir)
    if (not path.is_absolute() or '..' in path.parts or path.name != args.title or
            any(c in args.remote_dir for c in ('\r', '\n', '\\'))):
        p.error('--remote-dir must be the full path ending in ' + args.title)
    meta = args.src / 'sce_sys/param.json'
    if meta.is_file() and json.loads(meta.read_text(encoding='utf-8')).get('titleId') != args.title:
        p.error('Title ID in metadata does not match the source folder')
    items = []
    for source in files(args.src):
        rel = source.relative_to(args.src)
        if personal_path(rel, args.title) or '.before-' in source.name:
            continue
        items.append((source, rel.as_posix()))
    validate_names(items)
    if not items:
        p.error('No transferable files in selected folder')
    print(args.title + ': ' + str(len(items)) + ' files selected; saves excluded, existing configuration preserved.')
    if args.check:
        return
    ftp_copy(items, args)



def validate_prepared(root, manifest):
    """Read-only checks against a preparation-time inventory, never a new baseline."""
    if root.name not in PORTS:
        raise ValueError('--src must be the PPSAxxxxx folder itself, not its parent')
    actual = files(root)  # Reject symlinks before opening any inventoried file.
    data = json.loads(manifest.read_text(encoding='utf-8'))
    if (not isinstance(data, dict) or type(data.get('schema')) is not int or data['schema'] != 1 or
            data.get('title') != root.name or data.get('mode') not in ('app', 'game', 'full') or
            not isinstance(data.get('files'), list) or not data['files']):
        raise ValueError('Invalid manifest schema, title, mode or empty inventory')
    expected = {}
    folded = set()
    for entry in data['files']:
        if not isinstance(entry, dict):
            raise ValueError('Invalid manifest file entry')
        name, size, sha256 = entry.get('path'), entry.get('size'), entry.get('sha256')
        if (not isinstance(name, str) or not name or PurePosixPath(name).is_absolute() or
                any(c in name for c in ('\\', ':', '\r', '\n')) or
                any(part in ('', '.', '..') for part in name.split('/')) or
                name.casefold() in folded or type(size) is not int or size < 0 or
                not isinstance(sha256, str) or len(sha256) != 64 or
                any(c not in '0123456789abcdef' for c in sha256)):
            raise ValueError('Invalid or duplicate manifest path, size or SHA-256')
        folded.add(name.casefold())
        expected[name] = (size, sha256)
    errors = []
    checked_bytes = 0
    for index, (name, (size, sha256)) in enumerate(expected.items(), 1):
        path = root / name
        print('[%d/%d] Checking %s' % (index, len(expected), name), flush=True)
        if not path.is_file():
            errors.append('Missing file: ' + name)
        elif path.stat().st_size != size:
            errors.append('Size mismatch: ' + name)
        elif digest(path) != sha256:
            errors.append('SHA-256 mismatch: ' + name)
        else:
            checked_bytes += size
    mode = data['mode']
    # A self-consistent inventory must still contain the selected installation parts.
    if mode in ('app', 'full'):
        for name in ('eboot.bin', 'sce_sys/param.json', 'sce_sys/icon0.png'):
            if name not in expected:
                errors.append('App inventory is incomplete: ' + name)
        try:
            meta = json.loads((root / 'sce_sys/param.json').read_text(encoding='utf-8'))
            if not isinstance(meta, dict) or meta.get('titleId') != root.name:
                errors.append('App metadata title ID does not match the folder')
        except (OSError, ValueError):
            errors.append('App metadata is missing or invalid')
    if mode in ('game', 'full'):
        target = PORTS[root.name][2]
        try:
            selected = game_files(root.name, root / target)
            for _, name in selected:
                if name not in expected:
                    errors.append('Game file not covered by manifest: ' + name)
        except (OSError, ValueError, zipfile.BadZipFile) as error:
            errors.append('Game layout: ' + str(error))
    extras = sorted(p.relative_to(root).as_posix() for p in actual
                    if p.relative_to(root).as_posix() not in expected)
    return {'title': root.name, 'mode': mode, 'ok': not errors,
            'files': len(expected), 'verified_bytes': checked_bytes,
            'errors': errors, 'untracked_files': extras,
            'scope': 'Preparation-time integrity and expected layout; not game authenticity, module ABI or gameplay.'}


def validation_main(argv=None):
    p = argparse.ArgumentParser(description='Offline, read-only SHA-256 and layout verification of a prepared title folder.')
    p.add_argument('--version', action='version', version=VERSION)
    p.add_argument('--src', required=True, type=Path, help='Prepared PPSAxxxxx folder, including a copy on USB')
    p.add_argument('--manifest', type=Path, help='Original MANIFEST-PPSAxxxxx.json; default: beside --src')
    p.add_argument('--require-complete', action='store_true', help='Fail unless the manifest includes both app and game')
    p.add_argument('--report', type=Path, help='Optional new JSON report outside the title folder; existing files are never replaced')
    if argv is None and len(sys.argv) == 1:
        source = input('Prepared PPSAxxxxx folder to check: ').strip().strip('"').strip("'")
        original = input('Original manifest path (blank: beside that folder): ').strip().strip('"').strip("'")
        argv = ['--src', source] + (['--manifest', original] if original else [])
    args = p.parse_args(argv)
    if args.report and (args.report.resolve() == args.src.resolve() or args.src.resolve() in args.report.resolve().parents):
        p.error('--report must be outside the title folder')
    manifest = args.manifest or args.src.parent / ('MANIFEST-' + args.src.name + '.json')
    if not manifest.is_file():
        raise ValueError('Missing original checksum manifest: ' + str(manifest) +
                         '. Prepare a new folder with helper v1.1.0+; do not invent a baseline for suspect files.')
    result = validate_prepared(args.src, manifest)
    if args.require_complete and result['mode'] != 'full':
        result['errors'].append('A complete app-plus-game folder is required; this manifest is ' + result['mode'] + '-only')
        result['ok'] = False
    if args.report:
        with args.report.open('x', encoding='utf-8') as stream:
            json.dump(result, stream, indent=2)
            stream.write('\n')
    for error in result['errors']:
        print('FAIL: ' + error)
    if result['untracked_files']:
        print('%d additional files are NOT covered by this manifest (see --report).' % len(result['untracked_files']))
    if result['ok']:
        print('PASS: %d inventoried files match SHA-256; %s folder layout checked.' % (result['files'], result['mode']))
    if result['mode'] == 'app':
        print('App only: required private game files are still missing from this preparation.')
    elif result['mode'] == 'game':
        print('Game-data overlay only: the app must already be installed separately.')
    print(result['scope'])
    if not result['ok']:
        raise SystemExit(1)


def run_cli(action):
    try:
        action()
    except (ValueError, OSError, zipfile.BadZipFile, ftplib.Error, KeyError, EOFError) as error:
        print('Setup stopped: ' + str(error), file=sys.stderr)
        sys.exit(1)


