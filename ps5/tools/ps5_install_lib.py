    if args.title not in PORTS:
        p.error('--src must be the prepared PPSAxxxxx folder')
    if args.install_root:
        args.remote_dir = args.install_root.rstrip('/') + '/' + args.title
    metadata = args.src / 'sce_sys/param.json'
    if metadata.is_file() and json.loads(metadata.read_text(encoding='utf-8')).get('titleId') != args.title:
        p.error('Selected folder and metadata title ID differ')
